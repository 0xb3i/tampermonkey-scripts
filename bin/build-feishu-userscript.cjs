#!/usr/bin/env node
'use strict';

// Build helper for the Feishu Tampermonkey userscript.
//
// The userscript must ship as a single file installable in Tampermonkey, but
// most of its logic now lives in `lib/feishu-*.cjs` so that pure functions can
// be unit-tested under Node.  This script glues the lib modules into a
// browser-compatible runtime block, replaces the
// `// __FEISHU_HELPER_LIB_INLINE__` marker in the userscript source, and
// writes the result back in-place.

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const USERSCRIPT_PATH = path.join(ROOT, 'userscripts/feishu-helper.user.js');
const MARKER = '// __FEISHU_HELPER_LIB_INLINE__';

const LIB_MODULES = [
  'lib/feishu-attribs.cjs',
  'lib/feishu-style-codec.cjs',
  'lib/feishu-html-sanitizer.cjs',
  'lib/feishu-docx-record.cjs',
  'lib/feishu-block-render.cjs',
  'lib/feishu-semantic-snapshot.cjs',
];

function moduleNameFromPath(filePath) {
  return path.basename(filePath, path.extname(filePath))
    .replace(/^feishu-/, '')
    .replace(/-([a-z])/g, function (_, ch) { return ch.toUpperCase(); });
}

// Wrap the CJS source so we expose `module.exports` to the next module via
// the FeishuHelperLibs container.  Each lib must have a `module.exports`
// assignment as its last statement.
function inlineLibSources() {
  const wrappers = LIB_MODULES.map(function (relativePath) {
    const absolutePath = path.join(ROOT, relativePath);
    const source = fs.readFileSync(absolutePath, 'utf8');
    const moduleName = moduleNameFromPath(relativePath);
    return [
      '  // ── ' + relativePath + ' ──',
      '  FeishuHelperLibs.' + moduleName + ' = (function () {',
      '    var module = { exports: {} };',
      '    var exports = module.exports;',
      '    (function () {',
      indentSource(source, 6),
      '    })();',
      '    return module.exports;',
      '  })();',
    ].join('\n');
  });

  return [
    '  var FeishuHelperLibs = {};',
    wrappers.join('\n\n'),
  ].join('\n');
}

function indentSource(source, spaces) {
  const indent = ' '.repeat(spaces);
  return source.split('\n').map(function (line) {
    return line ? indent + line : line;
  }).join('\n');
}

function build() {
  const userscript = fs.readFileSync(USERSCRIPT_PATH, 'utf8');
  if (userscript.indexOf(MARKER) === -1) {
    throw new Error(
      'Cannot find inline marker "' + MARKER + '" in '
      + path.relative(ROOT, USERSCRIPT_PATH)
    );
  }

  const inlinedHeader = '// ── BEGIN inlined lib/* (generated by bin/build-feishu-userscript.cjs) ──';
  const inlinedFooter = '// ── END inlined lib/* ──';
  const banner = ['', inlinedHeader, inlineLibSources(), inlinedFooter, ''].join('\n');

  // Find any previously-inlined block plus the marker, then splice.  We avoid
  // String.prototype.replace because the replacement contains `$` which the
  // built-in replacer treats specially.
  const beginIndex = userscript.indexOf(inlinedHeader);
  const markerIndex = userscript.indexOf(MARKER);
  if (markerIndex === -1) {
    throw new Error('marker not found');
  }
  const sliceStart = beginIndex >= 0 ? beginIndex : markerIndex;
  // Skip backwards over a single trailing newline so we don't accumulate blank
  // lines on every rebuild.
  const before = userscript.slice(0, sliceStart).replace(/\n+$/, '\n');
  const afterMarker = userscript.slice(markerIndex);
  const next = before + banner + afterMarker;

  if (next === userscript) {
    console.log('[build-feishu-userscript] no changes detected; skipping write');
    return;
  }

  fs.writeFileSync(USERSCRIPT_PATH, next);
  console.log('[build-feishu-userscript] wrote ' + path.relative(ROOT, USERSCRIPT_PATH));
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

if (require.main === module) {
  try {
    build();
  } catch (error) {
    console.error('[build-feishu-userscript] failed:', error && error.message ? error.message : error);
    process.exitCode = 1;
  }
}

module.exports = {
  build: build,
};
