  function getImageInfoFromTarget(target) {
    var img = target && target.closest && target.closest('img');
    if (img) {
      var src = img.currentSrc || img.src || img.getAttribute('data-src') || img.getAttribute('data-original');
      if (!src) return null;
      return {
        src: src,
        alt: img.alt || '',
        width: img.naturalWidth || img.width || 0,
        height: img.naturalHeight || img.height || 0,
        element: img,
        sourceType: 'img',
      };
    }
    var el = target;
    var bgUrl = '';
    while (el && el !== document.documentElement) {
      if (el.nodeType === 1) {
        var bg = getComputedStyle(el).backgroundImage || '';
        bgUrl = extractUrlFromBackgroundImage(bg);
        if (bgUrl) break;
      }
      el = el.parentElement;
    }
    if (!el || !bgUrl) return null;
    return {
      src: bgUrl,
      alt: '',
      width: el.offsetWidth || 0,
      height: el.offsetHeight || 0,
      element: el,
      sourceType: 'background',
    };
  }

  function copyImageBlobToClipboard(url) {
    return originalFetch(url, { credentials: 'include' }).then(function (res) {
      if (!res.ok) throw new Error('fetch failed');
      return res.blob();
    }).then(function (blob) {
      if (!navigator.clipboard || !navigator.clipboard.write) {
        throw new Error('clipboard unavailable');
      }
      var type = blob.type || 'image/png';
      var item = {};
      item[type] = blob;
      return navigator.clipboard.write([new ClipboardItem(item)]);
    });
  }

