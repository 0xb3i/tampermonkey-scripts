        CSS_TO_FEISHU_BORDER_COLOR: CSS_TO_FEISHU_BORDER_COLOR,
        CSS_TO_FEISHU_TEXT_COLOR: CSS_TO_FEISHU_TEXT_COLOR,
        EMOJI_MAP: EMOJI_MAP,
        FEISHU_BG_COLOR_TO_CSS: FEISHU_BG_COLOR_TO_CSS,
